// Package diagnosis is the Diagnosis bounded context: one on-device classification
// result that a phone syncs to the backend. Pure domain code: no SQL, no HTTP.
package diagnosis

import (
	"context"
	"regexp"
	"strings"
	"time"

	"github.com/Paulmburu/ai-crop-disease-platform/go-backend/internal/domain/shared"
)

// Status mirrors the ML service and the phone: "ok" when confidence reaches the
// model's threshold, otherwise "uncertain" (the app asked the user to retake the photo).
type Status string

const (
	StatusOK        Status = "ok"
	StatusUncertain Status = "uncertain"
)

// MaxClockSkew tolerates phones whose clock runs slightly ahead of the server.
const MaxClockSkew = 5 * time.Minute

var uuidRE = regexp.MustCompile(`^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$`)

// Diagnosis is the aggregate root. Fields are unexported so every instance goes
// through NewDiagnosis (or Rehydrate for data already validated and stored).
type Diagnosis struct {
	id                  string
	deviceID            string
	classLabel          string
	confidence          float64
	confidenceThreshold float64
	modelVersion        string
	capturedAt          time.Time
	recordedAt          time.Time
}

// NewInput is what a caller provides; Status is derived, never supplied.
type NewInput struct {
	ID                  string // client-generated UUID: the idempotency key
	DeviceID            string
	ClassLabel          string // exact classifier label, e.g. "Potato___Late_blight"
	Confidence          float64
	ConfidenceThreshold float64 // the threshold the phone's model used
	ModelVersion        string
	CapturedAt          time.Time
}

// NewDiagnosis validates every invariant and returns a new aggregate.
func NewDiagnosis(in NewInput, now time.Time) (*Diagnosis, error) {
	switch {
	case !uuidRE.MatchString(in.ID):
		return nil, shared.Invalid("invalid_id", "id must be a UUID generated by the client")
	case strings.TrimSpace(in.DeviceID) == "":
		return nil, shared.Invalid("invalid_device_id", "device_id is required")
	case strings.TrimSpace(in.ClassLabel) == "":
		return nil, shared.Invalid("invalid_class_label", "class_label is required")
	case in.Confidence < 0 || in.Confidence > 1:
		return nil, shared.Invalid("invalid_confidence", "confidence must be between 0 and 1")
	case in.ConfidenceThreshold < 0 || in.ConfidenceThreshold > 1:
		return nil, shared.Invalid("invalid_threshold", "confidence_threshold must be between 0 and 1")
	case strings.TrimSpace(in.ModelVersion) == "":
		return nil, shared.Invalid("invalid_model_version", "model_version is required")
	case in.CapturedAt.IsZero():
		return nil, shared.Invalid("invalid_captured_at", "captured_at is required")
	case in.CapturedAt.After(now.Add(MaxClockSkew)):
		return nil, shared.Invalid("invalid_captured_at", "captured_at is in the future")
	}
	return &Diagnosis{
		id: strings.ToLower(in.ID), deviceID: in.DeviceID, classLabel: in.ClassLabel,
		confidence: in.Confidence, confidenceThreshold: in.ConfidenceThreshold,
		modelVersion: in.ModelVersion, capturedAt: in.CapturedAt.UTC(), recordedAt: now.UTC(),
	}, nil
}

// Rehydrate rebuilds a stored aggregate (used by repositories only).
func Rehydrate(in NewInput, recordedAt time.Time) *Diagnosis {
	return &Diagnosis{
		id: in.ID, deviceID: in.DeviceID, classLabel: in.ClassLabel, confidence: in.Confidence,
		confidenceThreshold: in.ConfidenceThreshold, modelVersion: in.ModelVersion,
		capturedAt: in.CapturedAt.UTC(), recordedAt: recordedAt.UTC(),
	}
}

func (d *Diagnosis) ID() string                   { return d.id }
func (d *Diagnosis) DeviceID() string             { return d.deviceID }
func (d *Diagnosis) ClassLabel() string           { return d.classLabel }
func (d *Diagnosis) Confidence() float64          { return d.confidence }
func (d *Diagnosis) ConfidenceThreshold() float64 { return d.confidenceThreshold }
func (d *Diagnosis) ModelVersion() string         { return d.modelVersion }
func (d *Diagnosis) CapturedAt() time.Time        { return d.capturedAt }
func (d *Diagnosis) RecordedAt() time.Time        { return d.recordedAt }

// Status is derived from confidence and the model's threshold, the same rule everywhere.
func (d *Diagnosis) Status() Status {
	if d.confidence >= d.confidenceThreshold {
		return StatusOK
	}
	return StatusUncertain
}

// IsHealthy is true for "…healthy" labels with an ok status.
func (d *Diagnosis) IsHealthy() bool {
	return d.Status() == StatusOK && strings.HasSuffix(strings.ToLower(d.classLabel), "healthy")
}

// Repository is the persistence port for diagnoses (implemented in infrastructure).
type Repository interface {
	// Save stores d unless a diagnosis with the same id exists. It returns
	// created=false (and no error) for an existing id, which makes sync idempotent.
	Save(ctx context.Context, d *Diagnosis) (created bool, err error)
	// FindByID returns a shared.KindNotFound error when the id is unknown.
	FindByID(ctx context.Context, id string) (*Diagnosis, error)
}
